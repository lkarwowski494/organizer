const root = fileURLToPath(new URL('..', import.meta.url));
const plPath = join(root, 'src/i18n/strings.pl.ts');
const enPath = join(root, 'src/i18n/strings.en.ts');

const src = readFileSync(plPath, 'utf8').replace(/\r\n/g, '\n');
const lines = src.split('\n');

let inObj = false;
let currentKey = null;
let currentVal = [];
const allEntries = [];

for (let i = 0; i < lines.length; i++) {
  const l = lines[i];
  if (l.includes('export const strings = {')) {
    inObj = true;
    continue;
  }
  if (inObj && l.startsWith('}')) {
    if (currentKey) allEntries.push({ key: currentKey, val: currentVal.join('\n') });
    break;
  }
  if (!inObj) continue;
  const m = l.match(/^\s*'([^']+)'\s*:/);
  if (m) {
    if (currentKey) allEntries.push({ key: currentKey, val: currentVal.join('\n') });
    currentKey = m[1];
    currentVal = [l.slice(l.indexOf(':') + 1)];
  } else if (currentKey) {
    currentVal.push(l);
  }
}


